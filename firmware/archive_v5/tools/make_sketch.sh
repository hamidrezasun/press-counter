#!/bin/sh
# Assemble the Arduino-IDE sketch of the counter (STM32F103C8T6) in firmware/sketch/counter  - open counter.ino in the Arduino IDE and press Upload.
#
#   sh make_sketch.sh [out_dir]          (default: firmware/sketch/counter, the folder is rebuilt every time: never edit it, edit firmware/counter and firmware/shared)
#
# The sources live in firmware/counter/src, firmware/counter/include and firmware/shared; the Arduino IDE wants one flat sketch folder, so they are
# copied here.  build_opt.h carries the compiler flags (the STM32duino core reads it from the sketch folder).
set -e
HERE="$(cd "$(dirname "$0")" && pwd)"
FW="$HERE/.."
OUT="${1:-$FW/sketch/counter}"
rm -rf "$OUT"
mkdir -p "$OUT/src"
# the sources go into src/ (the Arduino IDE compiles it recursively): the header names (clock.h, bootloader.h ...) must not end up on the include path of the core libraries
cp "$FW"/counter/src/* "$OUT/src/"
cp "$FW"/counter/include/* "$OUT/src/"
cp "$FW"/shared/* "$OUT/src/"
cat > "$OUT/counter.ino" <<'EOF'
// Press counter - machine controller (STM32F103C8T6, v5 MAIN board).  The code is in the src folder (main.cpp ...).
// GENERATED by firmware/tools/make_sketch.sh from firmware/counter + firmware/shared - do not edit here.
//
// Arduino IDE settings (STM32duino core "STMicroelectronics:stm32" 3.0.0, library MFRC522):
//   Board: Generic STM32F1 series      Board part number: Generic F103C8Tx     USB support: CDC (generic 'Serial' supersede)
//   U(S)ART support: Enabled (generic 'Serial')     Optimize: Smallest (-Os default) + LTO       Upload method: HID Bootloader 2.2
// The first time the chip has to get the HID bootloader (ST-Link on J9, see docs/FIRMWARE.md); after that Upload works over the USB cable J3.
EOF
# flags the sketch needs: 8 MHz crystal, the application define, the hardware UART1 of the ESP link
cat > "$OUT/build_opt.h" <<'EOF'
-DHSE_VALUE=8000000U
-DPC_NODE_FIRMWARE
-DENABLE_HWSERIAL1
EOF
echo "sketch: $OUT"
