#!/usr/bin/env python3
"""Embeds the web pages (firmware/press_counter/data/*.html) into pc_page.h so that the firmware needs no file upload.

    python firmware/tools/embed_page.py

index.html is gzip-compressed (the browser inflates it); setup.html is small and stays plain text.
Run it again after every change of data/*.html and rebuild the firmware.
"""
import gzip
import os

HERE = os.path.dirname(os.path.abspath(__file__))
GW = os.path.join(HERE, "..", "press_counter")


def main():
    with open(os.path.join(GW, "data", "index.html"), "rb") as f:
        raw = f.read()
    gz = gzip.compress(raw, 9, mtime=0)
    with open(os.path.join(GW, "data", "setup.html"), "r", encoding="utf-8") as f:
        setup = f.read()
    assert ")rawliteral" not in setup
    out = ["// pc_page.h - GENERATED by firmware/tools/embed_page.py from data/index.html and data/setup.html. Do not edit.",
           "#ifndef PC_PAGE_H", "#define PC_PAGE_H", "#include <Arduino.h>", ""]
    out.append("static const size_t PAGE_INDEX_GZ_LEN = %d;   // %d bytes of HTML" % (len(gz), len(raw)))
    out.append("static const uint8_t PAGE_INDEX_GZ[] PROGMEM = {")
    for i in range(0, len(gz), 20):
        out.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 20]) + ",")
    out.append("};")
    out.append("")
    out.append('static const char PAGE_SETUP[] PROGMEM = R"rawliteral(%s)rawliteral";' % setup)
    out.append("")
    out.append("#endif")
    with open(os.path.join(GW, "pc_page.h"), "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print("pc_page.h: index %d -> %d bytes gzip, setup %d bytes" % (len(raw), len(gz), len(setup)))


if __name__ == "__main__":
    main()
